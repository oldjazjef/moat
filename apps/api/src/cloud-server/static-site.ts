import { readFileSync, statSync } from 'node:fs';
import { join, posix, resolve } from 'node:path';
import express, {
  type NextFunction,
  type Request,
  type RequestHandler,
  type Response,
} from 'express';

/**
 * The runtime configuration the dashboard reads before it boots (apps/web/public/env.js, which the
 * server never serves). The same for every deployment: the dashboard and the API share one origin
 * (`apiBaseUrl` empty), the mode is `cloud`. It carries no secret and no setting of this server (T-84).
 */
export const CLOUD_ENV_JS = `// Generated by the Moat Cloud server. Same origin; no secrets here.
window.__MT_ENV__ = {
  apiBaseUrl: '',
  authMode: 'cloud',
};
`;

/** A file name with the build's content hash (`main-YG4VST5K.js`): never changes, cache for good. */
const HASHED = /-[A-Za-z0-9_-]{8}\.(js|css|woff2?)$/;

/** Prefix of the API; everything below it belongs to Nest, never to the file server. */
export function isApiPath(path: string): boolean {
  return path === '/api' || path.startsWith('/api/');
}

/** `/env.js` however it is spelled (`//env.js`, `/./env.js`, `/%65nv.js`): always the generated one. */
function isEnvJs(path: string): boolean {
  try {
    const clean = posix.normalize(decodeURIComponent(path));
    return clean.replace(/^\/+/, '/') === '/env.js';
  } catch {
    return false;
  }
}

/** The last path segment has no extension: a page of the dashboard, not a file. */
function looksLikePage(path: string): boolean {
  const last = path.slice(path.lastIndexOf('/') + 1);
  return !last.includes('.');
}

/** A browser navigation asks for HTML; a script, a `curl` or a probe does not get the shell. */
function acceptsHtml(request: Request): boolean {
  return (request.headers.accept ?? '').toLowerCase().includes('text/html');
}

function send(
  response: Response,
  type: string,
  body: Buffer | string,
  head: boolean,
): void {
  response
    .status(200)
    .setHeader('Content-Type', type)
    .setHeader('Cache-Control', 'no-cache');
  if (head) response.end();
  else response.end(body);
}

/**
 * Serves the dashboard's build from one folder, from the same origin as the API (`/api/**` is not
 * touched). Strict by design:
 *
 * - only GET and HEAD, only regular files below the folder: `..` segments, encoded or not, dot
 *   files and malformed escapes never reach the file system (T-84);
 * - `/env.js` is generated (`CLOUD_ENV_JS`), whatever the folder holds;
 * - the SPA fallback (`index.html`, 200) only for a navigation: a path without an extension, an
 *   `Accept` with `text/html`, not under `/api`. A missing file, a script or a probe gets the
 *   normal 404 — a typo in an asset URL must not come back as HTML;
 * - `index.html` is read once at start: a folder without it refuses to start (fail closed).
 */
export function createStaticSite(directory: string): RequestHandler {
  const root = resolve(directory);
  let index: Buffer;
  try {
    if (!statSync(root).isDirectory()) throw new Error('not a directory');
    index = readFileSync(join(root, 'index.html'));
  } catch {
    throw new Error('MOAT_WEB_DIR does not hold the dashboard (index.html)');
  }
  const files = express.static(root, {
    index: false,
    dotfiles: 'ignore',
    redirect: false,
    fallthrough: true,
    etag: true,
    extensions: false,
    setHeaders: (response, path) => {
      response.setHeader(
        'Cache-Control',
        HASHED.test(path) ? 'public, max-age=31536000, immutable' : 'no-cache',
      );
    },
  });
  return (request: Request, response: Response, next: NextFunction): void => {
    if (request.method !== 'GET' && request.method !== 'HEAD') return next();
    const path = request.path;
    if (isApiPath(path)) return next();
    const head = request.method === 'HEAD';
    if (isEnvJs(path)) {
      return send(
        response,
        'text/javascript; charset=utf-8',
        CLOUD_ENV_JS,
        head,
      );
    }
    files(request, response, (error?: unknown) => {
      if (error !== undefined) {
        // A bad escape or an attempt to leave the folder: refused without a body or a reason.
        const status =
          typeof error === 'object' &&
          error !== null &&
          'status' in error &&
          error.status === 400
            ? 400
            : 404;
        response.status(status).end();
        return;
      }
      if (looksLikePage(path) && acceptsHtml(request)) {
        return send(response, 'text/html; charset=utf-8', index, head);
      }
      next();
    });
  };
}
