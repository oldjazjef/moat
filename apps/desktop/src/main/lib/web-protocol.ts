import type { AddressInfo } from 'node:net';
import { extname, join, normalize, resolve, sep } from 'node:path';

/**
 * The window loads `app://moat/…`, a privileged custom scheme served by the main process:
 * the Angular build from disk, `/api/…` proxied to the in-process API on its random loopback
 * port. Same origin for both — no CORS, the app's `apiBaseUrl` stays empty — and a **stable**
 * origin across starts, so localStorage (theme, …) survives although the port changes.
 */
export const APP_SCHEME = 'app';
export const APP_HOST = 'moat';
export const APP_ORIGIN = `${APP_SCHEME}://${APP_HOST}`;

/**
 * Strict CSP for the window. Only own files; `style-src 'unsafe-inline'` because Angular and the
 * spartan components set style attributes; no `unsafe-eval`, no remote hosts — the desktop app
 * loads nothing from the network (DT-08, DT-10).
 */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-src 'none'",
  "frame-ancestors 'none'",
].join('; ');

/** The runtime configuration the web app reads before it boots (see apps/web/public/env.js). */
